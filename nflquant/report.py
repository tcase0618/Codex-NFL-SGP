"""Render docs/nflquant-validation-report.md from stored validation artifacts.

Every number in the report is read from data/lake/*_validation.json written by the
pipeline; nothing is typed by hand.  Run: python -m nflquant.report
"""
from __future__ import annotations

import json
from pathlib import Path

from .config import ROOT, settings


def _load(name):
    p = settings().lake_dir / f"{name}_validation.json"
    return json.loads(p.read_text()) if p.exists() else None


def f(x, d=3):
    return "—" if x is None else (f"{x:.{d}f}" if isinstance(x, (int, float)) else str(x))


def pct(x, d=1):
    return "—" if x is None else f"{100 * x:.{d}f}%"


def render() -> str:
    g, p, m, s = _load("game"), _load("player"), _load("matchup"), _load("sim")
    meta_p = settings().lake_dir / "production_meta.json"
    meta = json.loads(meta_p.read_text()) if meta_p.exists() else {}
    L = ["# nflquant validation report", "",
         "Generated by `python -m nflquant.report` from the pipeline's stored validation artifacts. "
         "All evaluations are chronological: every prediction was produced by models fit only on earlier seasons, "
         "with features computed from games before kickoff.", ""]
    if meta:
        L += [f"Production models trained through **{meta.get('trained_through')}** "
              f"(game model `{meta.get('model_version')}`; {meta.get('n_upcoming_games')} unplayed games predicted).", ""]
    if g:
        e = g["models"]["ensemble"]
        L += ["## Game outcomes", "", f"Walk-forward test seasons {g['seasons'][0]}–{g['seasons'][1]}, **{g['n_games']} games**.", "",
              "| Model | Win log loss | Brier | Margin MAE | Margin RMSE | Total MAE |", "|---|---|---|---|---|---|"]
        for k, v in g["models"].items():
            L.append(f"| {k} | {f(v.get('log_loss'), 4)} | {f(v.get('brier'), 4)} | {f(v['margin_mae'], 2)} | {f(v['margin_rmse'], 2)} | {f(v['total_mae'], 2)} |")
        L += ["", f"* Ensemble: raw log loss {f(e['log_loss_raw'], 4)} → Platt-recalibrated {f(e['log_loss'], 4)}; "
                  f"ECE {pct(e['ece'], 2)}; straight-up accuracy {pct(e['accuracy'])}.",
              f"* Score MAE: home {f(e['home_points_mae'], 2)}, away {f(e['away_points_mae'], 2)} points.",
              f"* Interval coverage: margin 80% PI {pct(e['margin_80pi_coverage'])}, 50% PI {pct(e['margin_50pi_coverage'])}; "
              f"total 80% PI {pct(e['total_80pi_coverage'])}."]
        mk = g.get("market_benchmark")
        if mk:
            L += ["", "**Closing-market benchmark** (nflverse schedule lines; never a model input):", "",
                  "| | Model | Market |", "|---|---|---|",
                  f"| Margin MAE | {f(mk['margin_mae_model'], 3)} | {f(mk['margin_mae_market'], 3)} |",
                  f"| Total MAE | {f(mk['total_mae_model'], 3)} | {f(mk['total_mae_market'], 3)} |",
                  f"| Win log loss | {f(mk['log_loss_model'], 4)} | {f(mk['log_loss_market'], 4)} |",
                  f"| Brier | {f(mk['brier_model'], 4)} | {f(mk['brier_market'], 4)} |", "",
                  "The closing market is more accurate on every measure. The model is an independent, market-free forecast; "
                  "no betting edge is claimed."]
        L += ["", "Calibration (home-win probability, 10 bins):", "", "| Bin | n | Mean predicted | Observed |", "|---|---|---|---|"]
        for r in g["reliability"]:
            L.append(f"| {r['bin_lo']:.1f}–{r['bin_hi']:.1f} | {r['n']} | {r['mean_pred']:.3f} | {r['observed']:.3f} |")
        L += ["", "Segments:", "", "| Segment | n | Log loss | Brier | Margin MAE | Total MAE |", "|---|---|---|---|---|---|"]
        for r in g["segments"]:
            L.append(f"| {r['segment']} | {r['n']} | {f(r['log_loss'], 4)} | {f(r['brier'], 4)} | {f(r['margin_mae'], 2)} | {f(r['total_mae'], 2)} |")
        L.append("")
    if p:
        L += ["## Player stat projections", "",
              "Baseline = player's EWMA (half-life 4 games). Skill = 1 − MAE / baseline MAE. Projected players who then "
              "recorded nothing are scored as 0 (real forecast error). Intervals: multi-quantile boosting for yards, "
              "negative-binomial for counts.", "",
              "| Target | n | MAE | Baseline MAE | Skill | Bias | 80% cov | 50% cov | P(≥1) Brier | P(≥1) ECE |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for k, v in p["targets"].items():
            L.append(f"| {k} | {v['n']} | {f(v['mae'], 3)} | {f(v['baseline_mae'], 3)} | {pct(v.get('skill_vs_baseline'))} | "
                     f"{f(v['bias'], 3)} | {pct(v['coverage_80'])} | {pct(v['coverage_50'])} | {f(v.get('p_ge1_brier'), 4)} | {pct(v.get('p_ge1_ece'), 2)} |")
        seasons = next(iter(p["targets"].values()))["seasons"]
        L += ["", f"Test seasons {seasons[0]}–{seasons[1]}. Segment breakdowns (position, season, home/away, questionable, "
                  "opponent pass defense, dome, wind) are in `data/lake/player_validation.json` and the Model Audit workspace.", ""]
    if m:
        L += ["## Unit-matchup models", "", f"Held-out seasons {m['held_out_seasons']} (trained on 2016–2023).", "",
              "| Model | n test | Log loss | Base-rate log loss | Brier | Base-rate Brier | R² |", "|---|---|---|---|---|---|---|"]
        for unit in ("pass", "run"):
            for k, v in m[unit].items():
                L.append(f"| {unit} · {k} | {v['n_test']} | {f(v.get('log_loss'), 4)} | {f(v.get('log_loss_base_rate'), 4)} | "
                         f"{f(v.get('brier'), 4)} | {f(v.get('brier_base_rate'), 4)} | {f(v.get('r2'), 4)} |")
        L += ["", "Play-level outcomes are dominated by noise; models that do not beat the base rate are reported as such "
                  "and their matchup impacts should be read as near-zero.", ""]
    if s:
        L += ["## Simulation backtest", "", f"{s['n_games']} completed games ({s['scope']}), {s['n_sims_per_game']} simulations each, "
              "simulated from walk-forward pregame inputs only.", "",
              f"* Win log loss: simulation {f(s['log_loss_sim'], 4)} vs game model {f(s['log_loss_model'], 4)}; "
              f"Brier {f(s['brier_sim'], 4)} vs {f(s['brier_model'], 4)}.",
              f"* Margin 80% interval coverage {pct(s['margin_cov80'])}; total {pct(s['total_cov80'])}.",
              f"* Mean simulated margin σ {f(s['mean_sim_margin_sd'], 2)} vs empirical residual σ {f(s['empirical_margin_resid_sd'], 2)}.",
              f"* Overtime rate simulated {pct(s.get('sim_ot_rate'), 2)} vs observed {pct(s.get('observed_ot_rate'), 2)}; "
              f"ties simulated {pct(s.get('sim_tie_rate'), 2)} vs observed {pct(s.get('observed_tie_rate'), 2)}.",
              f"* Accounting identities held in every simulation: **{s['all_identities_hold']}**.", "",
              "| Player stat | n | MAE (sim mean) | MAE (ML mean) | Sim 80% coverage |", "|---|---|---|---|---|"]
        for k, v in s["player"].items():
            L.append(f"| {k} | {v['n']} | {f(v['mae_sim'], 3)} | {f(v['mae_ml'], 3)} | {pct(v['cov80'])} |")
        L.append("")
    L += ["## What these results do not show", "",
          "* No profitable betting strategy or edge over closing lines is claimed or demonstrated.",
          "* Injury reports and weather come from the nflverse copy retrieved after the fact; publication-time ordering "
          "is asserted by the source process, not by stored timestamps (2025+ depth charts do carry snapshot times).",
          "* Coverage/pressure/personnel metrics exist only for 2016–2025; 2026 participation was not published upstream at build time.",
          "* Individual coverage, blocking and pass-rush attribution are not public; on-field metrics are team outcomes.", ""]
    return "\n".join(L)


def main():
    out = ROOT / "docs" / "nflquant-validation-report.md"
    out.write_text(render())
    print(out)


if __name__ == "__main__":
    main()
